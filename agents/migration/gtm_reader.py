"""Read Google Tag Manager container via API."""

from google.oauth2 import service_account
from googleapiclient.discovery import build


class GTMReader:
    def __init__(self, account_id: str, container_id: str, credentials_path: str):
        self.account_id = account_id
        self.container_id = container_id
        self.credentials = service_account.Credentials.from_service_account_file(
            credentials_path,
            scopes=[
                "https://www.googleapis.com/auth/tagmanager.readonly",
                "https://www.googleapis.com/auth/tagmanager.edit.containers",
                "https://www.googleapis.com/auth/tagmanager.manage.accounts",
            ],
        )
        self.service = build("tagmanager", "v2", credentials=self.credentials)
        self._container_path = (
            f"accounts/{account_id}/containers/{container_id}"
        )
        self._workspace_path: str | None = None

    def _workspace_parent(self) -> str:
        if self._workspace_path:
            return self._workspace_path
        result = (
            self.service.accounts()
            .containers()
            .workspaces()
            .list(parent=self._container_path)
            .execute()
        )
        workspaces = result.get("workspace", [])
        if not workspaces:
            raise RuntimeError(f"No GTM workspaces in container {self.container_id}")
        default = next(
            (w for w in workspaces if w.get("name") == "Default Workspace"),
            workspaces[0],
        )
        self._workspace_path = default["path"]
        return self._workspace_path

    def get_tags(self) -> list[dict]:
        parent = self._workspace_parent()
        result = self.service.accounts().containers().workspaces().tags().list(
            parent=parent
        ).execute()
        tags = []
        for tag in result.get("tag", []):
            tags.append({
                "name": tag.get("name"),
                "type": tag.get("type"),
                "firing_trigger_id": tag.get("firingTriggerId", []),
                "parameter": tag.get("parameter", []),
                "tag_id": tag.get("tagId"),
            })
        return tags

    def get_triggers(self) -> list[dict]:
        parent = self._workspace_parent()
        result = self.service.accounts().containers().workspaces().triggers().list(
            parent=parent
        ).execute()
        triggers = []
        for trigger in result.get("trigger", []):
            triggers.append({
                "name": trigger.get("name"),
                "type": trigger.get("type"),
                "trigger_id": trigger.get("triggerId"),
                "custom_event_filter": trigger.get("customEventFilter", []),
            })
        return triggers

    def get_variables(self) -> list[dict]:
        parent = self._workspace_parent()
        result = self.service.accounts().containers().workspaces().variables().list(
            parent=parent
        ).execute()
        variables = []
        for var in result.get("variable", []):
            variables.append({
                "name": var.get("name"),
                "type": var.get("type"),
                "variable_id": var.get("variableId"),
                "parameter": var.get("parameter", []),
            })
        return variables

    MIGRATION_WORKSPACE_NAME = "OYDK Migration Draft"

    def create_migration_workspace(self, name: str = "OYDK Migration Draft") -> dict:
        """Create a new GTM workspace for migration changes (draft only)."""
        result = (
            self.service.accounts()
            .containers()
            .workspaces()
            .create(
                parent=self._container_path,
                body={
                    "name": name,
                    "description": (
                        "Auto-generated by Own-Your-Data Kit migration agent. "
                        "Review before publishing."
                    ),
                },
            )
            .execute()
        )
        self._workspace_path = result.get("path")
        return {
            "workspace_id": result.get("workspaceId"),
            "workspace_path": result.get("path"),
            "name": result.get("name"),
        }

    def get_or_create_migration_workspace(self) -> dict:
        """Return OYDK draft workspace, creating it if the API allows."""
        listed = (
            self.service.accounts()
            .containers()
            .workspaces()
            .list(parent=self._container_path)
            .execute()
        )
        for workspace in listed.get("workspace", []):
            if workspace.get("name") == self.MIGRATION_WORKSPACE_NAME:
                return {
                    "workspace_id": workspace.get("workspaceId"),
                    "workspace_path": workspace.get("path"),
                    "name": workspace.get("name"),
                    "created": False,
                }
        try:
            created = self.create_migration_workspace(self.MIGRATION_WORKSPACE_NAME)
            created["created"] = True
            return created
        except Exception as exc:
            return {
                "workspace_id": None,
                "workspace_path": None,
                "name": self.MIGRATION_WORKSPACE_NAME,
                "created": False,
                "error": str(exc),
            }

    def get_full_container(self) -> dict:
        return {
            "account_id": self.account_id,
            "container_id": self.container_id,
            "tags": self.get_tags(),
            "triggers": self.get_triggers(),
            "variables": self.get_variables(),
        }
